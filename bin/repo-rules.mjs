#!/usr/bin/env node
import { repoFacts } from "../lib/repo.mjs";
import { detectDeclared } from "../lib/detect.mjs";
import { validateRuleSet } from "../lib/validate.mjs";
import { expire } from "../lib/evidence.mjs";
import { load, save } from "../lib/rules-store.mjs";

const USAGE = "usage: repo-rules <scan|check|render>";

function reportWrite({ foreign, removed }) {
  for (const name of foreign) {
    console.log(`left .claude/rules/${name} alone: it was not generated by repo-rules`);
  }
  for (const name of removed) {
    console.log(`removed .claude/rules/${name}: no rule for this topic remains`);
  }
}

function reportDropped(dropped) {
  for (const item of dropped) console.log(`dropped ${item.id}: ${item.reasons.join("; ")}`);
}

function scan(facts) {
  const { accepted, rejected } = validateRuleSet(detectDeclared(facts.repoRoot));
  reportWrite(save(facts, accepted, process.env));
  reportDropped(rejected);
  console.log(`scan complete: ${accepted.length} rules, ${rejected.length} dropped`);
}

function check(facts) {
  const { found, rules, dropped } = load(facts, process.env);
  if (!found) {
    console.log("no rules for this repo; run repo-rules scan");
    return;
  }
  reportDropped(dropped);
  const { live, expired } = expire(rules, facts.repoRoot);
  reportWrite(save(facts, live, process.env));
  for (const item of expired) console.log(`expired ${item.id}: ${item.reason}`);
  console.log(`check complete: ${live.length} live, ${expired.length} expired`);
}

function renderOnly(facts) {
  const { found, rules, dropped } = load(facts, process.env);
  if (!found) {
    console.log("no rules for this repo; run repo-rules scan");
    return;
  }
  reportDropped(dropped);
  reportWrite(save(facts, rules, process.env));
  console.log(`render complete: ${rules.length} rules`);
}

const command = process.argv[2];
const facts = repoFacts(process.cwd());

// Outside a repository, repoRoot falls back to cwd itself. Without this guard scan would
// write .claude/repo-rules/ and reconcile .claude/rules/ in whatever directory it was run
// from, including a home directory Claude Code loads rules from for every project.
if (!facts.isGitRepo) {
  console.error("repo-rules: not a git repository");
  process.exit(1);
}

try {
  if (command === "scan") scan(facts);
  else if (command === "check") check(facts);
  else if (command === "render") renderOnly(facts);
  else {
    console.error(USAGE);
    process.exit(1);
  }
} catch (error) {
  console.error(`repo-rules: ${error.message}`);
  process.exit(1);
}
