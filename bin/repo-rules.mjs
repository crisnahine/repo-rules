#!/usr/bin/env node
import { readFileSync, existsSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import { repoFacts } from "../lib/repo.mjs";
import { detectDeclared } from "../lib/detect.mjs";
import { validateRuleSet } from "../lib/validate.mjs";
import { expire } from "../lib/evidence.mjs";
import { render, GENERATED_MARKER } from "../lib/render.mjs";
import { writeAtomic } from "../lib/io.mjs";

const USAGE = "usage: repo-rules <scan|check|render>";

function rulesPath(root) {
  return join(root, ".claude", "repo-rules", "rules.json");
}

function loadRules(root) {
  const path = rulesPath(root);
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, "utf8"));
}

function isGenerated(path) {
  try {
    return readFileSync(path, "utf8").includes(GENERATED_MARKER);
  } catch {
    return false;
  }
}

// Rewrite this plugin's own files each time so an expired topic leaves no orphan behind.
//
// Only files carrying the generated marker are ever removed or replaced. `.claude/rules/` is a
// directory Claude Code shares with whatever the team writes by hand, and deleting someone
// else's rules would be both destructive and invisible. Returns the names left alone so the
// caller can say so out loud.
function writeRuleset(root, rules) {
  writeAtomic(rulesPath(root), `${JSON.stringify(rules, null, 2)}\n`);
  const dir = join(root, ".claude", "rules");
  const files = render(rules);
  const existing = existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith(".md")) : [];

  const foreign = new Set(existing.filter((name) => !isGenerated(join(dir, name))));
  for (const name of existing) {
    if (!foreign.has(name) && !files.has(name)) rmSync(join(dir, name), { force: true });
  }

  if (files.size > 0) mkdirSync(dir, { recursive: true });
  for (const [name, body] of files) {
    if (foreign.has(name)) continue;
    writeAtomic(join(dir, name), body);
  }

  // Remove the directory only once this plugin has emptied it and nothing else lives there.
  if (files.size === 0 && existsSync(dir) && readdirSync(dir).length === 0) {
    rmSync(dir, { recursive: true, force: true });
  }

  return [...foreign].sort();
}

function reportForeign(names) {
  for (const name of names) {
    console.log(`left .claude/rules/${name} alone: it was not generated by repo-rules`);
  }
}

function scan(root) {
  const { accepted, rejected } = validateRuleSet(detectDeclared(root));
  reportForeign(writeRuleset(root, accepted));
  for (const item of rejected) console.log(`dropped ${item.id}: ${item.reasons.join("; ")}`);
  console.log(`scan complete: ${accepted.length} rules, ${rejected.length} dropped`);
}

function check(root) {
  const rules = loadRules(root);
  if (rules === null) {
    console.log("no rules for this repo; run repo-rules scan");
    return;
  }
  const { live, expired } = expire(rules, root);
  reportForeign(writeRuleset(root, live));
  for (const item of expired) console.log(`expired ${item.id}: ${item.reason}`);
  console.log(`check complete: ${live.length} live, ${expired.length} expired`);
}

function renderOnly(root) {
  const rules = loadRules(root);
  if (rules === null) {
    console.log("no rules for this repo; run repo-rules scan");
    return;
  }
  reportForeign(writeRuleset(root, rules));
  console.log(`render complete: ${rules.length} rules`);
}

const command = process.argv[2];
const root = repoFacts(process.cwd()).repoRoot;

try {
  if (command === "scan") scan(root);
  else if (command === "check") check(root);
  else if (command === "render") renderOnly(root);
  else {
    console.error(USAGE);
    process.exit(1);
  }
} catch (error) {
  console.error(`repo-rules: ${error.message}`);
  process.exit(1);
}
